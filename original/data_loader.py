"""
Data loader: turns the raw trade export (same column shape as the
historical CSV they've already sent, one Entry row + one Exit row per
Position_ID) into exactly the history format the model needs
(predict_live.score_new_trade's `history_df` argument).

This is deliberately decoupled from whatever API framework wraps it --
whether that's the standalone FastAPI app in api/, or a colleague's own
API kit calling this as a library function, the transformation is the
same: raw trade export -> paired trades -> model-ready history.

If the upstream export format turns out to differ from what's assumed here
(column names, one-row-per-trade instead of entry+exit rows, etc.), only
`load_raw_export` needs to change -- `to_model_history` and everything
downstream stays the same.
"""
import os
import pandas as pd

# Proprietary daily feature feed (F1..F139 style columns + a `date` column),
# generated by a separate, external process we don't have or need the code
# for -- we only ever read it from wherever it's stored. Path is
# environment/machine-specific (this dev box has a local copy for testing;
# the actual server location will differ), so it's configurable rather than
# hardcoded. Set GC_FEEDS_PATH, or pass `path=` explicitly.
FEEDS_PATH_ENV_VAR = "GC_FEEDS_PATH"


def load_raw_export(path_or_buffer) -> pd.DataFrame:
    """
    Parse a raw trade export (same shape as
    trades_TEST_COMBINED_GC_long_trend_strategy_*.csv) into one row per
    CLOSED position, keeping the fields the model pipeline cares about.
    """
    df = pd.read_csv(path_or_buffer, parse_dates=["Trade_Date"])
    df["entry_dt"] = pd.to_datetime(df["Trade_Date"].dt.date.astype(str) + " " + df["Trade_Time"])

    entries = df[df.Entry_Exit == "Entry"].set_index("Position_ID")
    exits = df[df.Entry_Exit == "Exit"].set_index("Position_ID")

    paired = pd.DataFrame({
        "entry_dt": entries["entry_dt"],
        "entry_price": entries["Avg_Entry_Price"],
        "take_profit": entries["Take_Profit"],
        "stop_loss": entries["Stop_Loss"],
        "exit_dt": exits["entry_dt"],
        "exit_date": exits["Trade_Date"],
        "exit_price": exits["Price"],
        "pnl": exits["Realized_PnL"],
        "exit_reason": exits["Notes"],
    }).dropna(subset=["pnl"])  # drop any still-open positions (no exit row yet)

    return paired.sort_values("entry_dt").reset_index().rename(columns={"Position_ID": "position_id"})


def to_model_history(paired: pd.DataFrame) -> pd.DataFrame:
    """Project down to exactly what predict_live.score_new_trade expects."""
    return paired[["entry_dt", "exit_dt", "exit_date", "exit_price", "pnl"]].copy()


def load_feeds(path: str = None) -> pd.DataFrame:
    """
    Read the proprietary daily feature feed from wherever it lives.
    Resolution order: explicit `path` argument, then GC_FEEDS_PATH env var.
    We don't generate or validate the content of these features here --
    just read the file and hand back a clean, date-indexed frame.
    """
    resolved = path or os.environ.get(FEEDS_PATH_ENV_VAR)
    if not resolved:
        raise ValueError(
            f"No feeds path given -- pass path= explicitly or set the "
            f"{FEEDS_PATH_ENV_VAR} environment variable to point at the feed "
            f"file's location on this machine."
        )
    feeds = pd.read_csv(resolved, parse_dates=["date"])
    return feeds.sort_values("date").reset_index(drop=True)


def attach_feeds_asof(trades: pd.DataFrame, feeds: pd.DataFrame, entry_col: str = "entry_dt",
                       lag_days: int = 1) -> pd.DataFrame:
    """
    Attach the most recent feeds row to each trade, as of `lag_days` before
    that trade's entry date.

    lag_days=1 (default) is the conservative choice: only use a feeds row
    from a STRICTLY PRIOR calendar day, matching the T-1 discipline used
    everywhere else in this model. This is intentional -- we don't yet have
    a confirmed timing/availability guarantee for this feed (i.e. whether a
    given day's row is finalized using only data available before that day's
    GC entries, or could reflect same-day information). Do not lower this to
    0 (same-day) until that's confirmed; doing so without confirmation risks
    silently reintroducing exactly the kind of look-ahead bias already ruled
    out for the take-profit feature.
    """
    t = trades.copy()
    t["_asof_date"] = pd.to_datetime(t[entry_col]).dt.normalize() - pd.Timedelta(days=lag_days)
    merged = pd.merge_asof(
        t.sort_values("_asof_date"),
        feeds.sort_values("date"),
        left_on="_asof_date", right_on="date",
        direction="backward",
    ).drop(columns=["_asof_date"])
    return merged.sort_values(entry_col).reset_index(drop=True)


def merge_incremental(existing: pd.DataFrame, new_raw_path_or_buffer, id_col="position_id") -> pd.DataFrame:
    """
    For repeated ingests (e.g. a daily export that may re-send trades already
    seen): parse the new export and merge into the existing paired-trades
    table, de-duplicating on position_id so re-sends are harmless.
    """
    new_paired = load_raw_export(new_raw_path_or_buffer)
    combined = pd.concat([existing, new_paired], ignore_index=True)
    combined = combined.drop_duplicates(subset=[id_col], keep="last")
    return combined.sort_values("entry_dt").reset_index(drop=True)


if __name__ == "__main__":
    # smoke test against the known historical file
    path = "<local-path>"
    paired = load_raw_export(path)
    print(f"Loaded {len(paired)} paired trades from raw export.")
    history = to_model_history(paired)
    print("Model-ready history columns:", history.columns.tolist())
    print(history.tail(3))

    # exercise the incremental merge path with a re-send of the same data (should be a no-op)
    merged = merge_incremental(paired, path)
    assert len(merged) == len(paired), "re-ingesting the same export should not duplicate rows"
    print(f"Incremental merge idempotency check passed: {len(merged)} rows after re-ingesting same file.")

    # smoke test the feeds attachment (using the local dev copy, not any server path)
    feeds = load_feeds(path="<local-path>")
    print(f"\nLoaded feeds: {feeds.shape[0]} rows x {feeds.shape[1]-1} feature columns, "
          f"{feeds['date'].min().date()} -> {feeds['date'].max().date()}")
    with_feeds = attach_feeds_asof(paired, feeds, lag_days=1)
    n_missing = with_feeds["F1"].isna().sum()
    print(f"Trades with a feeds row attached: {len(with_feeds) - n_missing} / {len(with_feeds)} "
          f"({n_missing} trades predate feed coverage or have no prior-day row)")
